package com.example.service

import android.content.Context
import android.content.Intent
import android.net.Uri
import androidx.core.content.FileProvider
import com.example.data.model.CapitalPlan
import com.example.data.model.GlobalPartner
import com.example.data.model.LaunchProject
import com.example.data.model.TrustEvidence
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.io.FileOutputStream
import java.nio.charset.StandardCharsets
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

object DocxExportService {

    suspend fun generateDocx(
        context: Context,
        project: LaunchProject,
        evidenceList: List<TrustEvidence>,
        partnerList: List<GlobalPartner>,
        capitalPlan: CapitalPlan?
    ): File = withContext(Dispatchers.IO) {
        val fileName = "Global_Launch_Dossier_${project.originCountry.replace("[^A-Za-z0-9]".toRegex(), "_")}_to_${project.targetCountry.replace("[^A-Za-z0-9]".toRegex(), "_")}.docx"
        val exportDir = File(context.cacheDir, "exports").apply { mkdirs() }
        val docxFile = File(exportDir, fileName)

        val documentXmlContent = buildDocumentXml(project, evidenceList, partnerList, capitalPlan)
        val contentTypesXml = buildContentTypesXml()
        val rootRelsXml = buildRootRelsXml()
        val wordRelsXml = buildWordRelsXml()
        val stylesXml = buildStylesXml()

        FileOutputStream(docxFile).use { fos ->
            ZipOutputStream(fos).use { zos ->
                // 1. [Content_Types].xml
                addZipEntry(zos, "[Content_Types].xml", contentTypesXml)
                // 2. _rels/.rels
                addZipEntry(zos, "_rels/.rels", rootRelsXml)
                // 3. word/_rels/document.xml.rels
                addZipEntry(zos, "word/_rels/document.xml.rels", wordRelsXml)
                // 4. word/styles.xml
                addZipEntry(zos, "word/styles.xml", stylesXml)
                // 5. word/document.xml
                addZipEntry(zos, "word/document.xml", documentXmlContent)
            }
        }

        docxFile
    }

    private fun addZipEntry(zos: ZipOutputStream, entryName: String, content: String) {
        val entry = ZipEntry(entryName)
        zos.putNextEntry(entry)
        val bytes = content.toByteArray(StandardCharsets.UTF_8)
        zos.write(bytes, 0, bytes.size)
        zos.closeEntry()
    }

    fun shareDocx(context: Context, file: File) {
        val uri: Uri = FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            file
        )

        val shareIntent = Intent(Intent.ACTION_SEND).apply {
            type = "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
            putExtra(Intent.EXTRA_STREAM, uri)
            putExtra(Intent.EXTRA_SUBJECT, "Global Product Bridge Dossier: ${file.name}")
            putExtra(Intent.EXTRA_TEXT, "Attached is the verified Global Launch Project & Trust Profile Dossier generated by Global Product Operating System.")
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }

        val chooser = Intent.createChooser(shareIntent, "Download or Open Generated DOCX")
        chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        context.startActivity(chooser)
    }

    private fun escapeXml(str: String): String {
        return str
            .replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace("\"", "&quot;")
            .replace("'", "&apos;")
    }

    private fun buildDocumentXml(
        project: LaunchProject,
        evidenceList: List<TrustEvidence>,
        partnerList: List<GlobalPartner>,
        capitalPlan: CapitalPlan?
    ): String {
        val timestamp = SimpleDateFormat("dd MMMM yyyy, HH:mm z", Locale.getDefault()).format(Date())

        val sb = StringBuilder()
        sb.append("<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\n")
        sb.append("<w:document xmlns:w=\"http://schemas.openxmlformats.org/wordprocessingml/2006/main\">\n")
        sb.append("<w:body>\n")

        // Title
        sb.append(paragraph("GLOBAL PRODUCT OPERATING SYSTEM", style = "Title", bold = true, color = "0A1128", fontSize = 48))
        sb.append(paragraph("GLOBAL LAUNCH PROJECT & TRUST DOSSIER", style = "Subtitle", bold = true, color = "D4AF37", fontSize = 32))
        sb.append(paragraph("Local Capability \u2192 Globally Trusted Product", italic = true, color = "64748B", fontSize = 22))
        sb.append(paragraph("Generated On: $timestamp | Corridor: ${project.originCountry} \u2192 ${project.targetCountry}", fontSize = 18, color = "94A3B8"))

        sb.append(divider())

        // Executive Thesis
        sb.append(heading("1. EXECUTIVE PRODUCT THESIS & CORRIDOR", 28))
        sb.append(paragraph(
            "Project Title: ${project.title}\n" +
            "Category: ${project.category}\n" +
            "Origin: ${project.originCountry} | Target Market: ${project.targetCountry}\n" +
            "Overall Readiness Index: ${project.overallReadiness}% (Website: ${project.websiteReadiness}%, Compliance: ${project.complianceReadiness}%, Supply: ${project.supplyReadiness}%, Distribution: ${project.distributionReadiness}%)",
            bold = false
        ))
        sb.append(paragraph(
            "Core Opportunity: ${project.description}\n" +
            "Market Gap in ${project.targetCountry}: ${project.marketGapSummary}",
            italic = false
        ))

        sb.append(divider())

        // Trust Profile
        sb.append(heading("2. GLOBAL TRUST PROFILE (VERIFIABLE EVIDENCE MOAT)", 28))
        sb.append(paragraph(
            "A global buyer or distributor does not look for unverified claims; they look for verifiable evidence infrastructure. Below is the 13-vector audit trail:",
            italic = true,
            color = "334155"
        ))

        for (item in evidenceList) {
            val statusColor = if (item.status == "VERIFIED") "10B981" else if (item.status == "IN_REVIEW") "F59E0B" else "E11D48"
            sb.append(paragraph(
                "[\u2713 ${item.status}] ${item.title} (${item.category})",
                bold = true,
                color = statusColor,
                fontSize = 22
            ))
            sb.append(paragraph(
                "Detail: ${item.detail}\n" +
                "Issuer / Proof: ${item.issuerOrEvidence}\n" +
                "Audit Stamp: ${item.evidenceHash} (${item.dateVerified})",
                fontSize = 18,
                color = "475569"
            ))
        }

        sb.append(divider())

        // Regulatory & Compliance
        sb.append(heading("3. REGULATORY COMPLIANCE & INTERNATIONAL LOGISTICS", 28))
        sb.append(paragraph("Regulatory Roadmap: ${project.regulatorySummary}"))
        sb.append(paragraph("Supply Chain & Batch Fingerprinting: ${project.supplySummary}"))
        sb.append(paragraph("Batch Provenance Code: ${project.batchCode}"))

        sb.append(divider())

        // Commercial Strategy
        sb.append(heading("4. COMMERCIALIZATION & POSITIONING", 28))
        sb.append(paragraph("Target Consumer Profile: ${project.targetCustomer}"))
        sb.append(paragraph("Pricing Architecture & Discovery Set: ${project.priceBenchmark}"))
        sb.append(paragraph("Go-To-Market Strategy: ${project.commercialSummary}"))

        sb.append(divider())

        // Partner Graph
        sb.append(heading("5. GLOBAL PARTNER GRAPH & FIT-SCORE MATRIX", 28))
        sb.append(paragraph("Fit Score Algorithm: Product Fit \u00D7 Market Fit \u00D7 Geography \u00D7 Capability \u00D7 Trust \u00D7 Cost \u00D7 Availability", italic = true))

        for (partner in partnerList) {
            sb.append(paragraph(
                "${partner.role}: ${partner.name} \u2014 ${partner.organization} (${partner.location})",
                bold = true,
                color = "0A1128"
            ))
            sb.append(paragraph(
                "Overall Fit Score: ${partner.totalFitScore}/100 | Status: ${partner.outreachStatus}\n" +
                "Profile: ${partner.description}\n" +
                "Action Brief: ${partner.samplePitchBrief}",
                fontSize = 18,
                color = "334155"
            ))
        }

        sb.append(divider())

        // Capital Engine
        sb.append(heading("6. CAPITAL REQUIREMENT & USE OF FUNDS ENGINE", 28))
        if (capitalPlan != null) {
            sb.append(paragraph("Total Capital Requirement: \u20AC${String.format(Locale.US, "%,d", capitalPlan.targetAmountEur)}", bold = true, color = "D4AF37", fontSize = 24))
            sb.append(paragraph(
                "\u2022 Manufacturing & Extraction: \u20AC${String.format(Locale.US, "%,d", capitalPlan.manufacturingEur)}\n" +
                "\u2022 EU Regulatory & Safety Dossier: \u20AC${String.format(Locale.US, "%,d", capitalPlan.complianceEur)}\n" +
                "\u2022 French 3PL Warehousing & Logistics: \u20AC${String.format(Locale.US, "%,d", capitalPlan.inventoryEur)}\n" +
                "\u2022 DTC Launch, Discovery Sets & Samples: \u20AC${String.format(Locale.US, "%,d", capitalPlan.marketingEur)}\n" +
                "\u2022 Selective Retailer Placement & Margin: \u20AC${String.format(Locale.US, "%,d", capitalPlan.distributionEur)}"
            ))
            sb.append(paragraph("Recommended Financing Instruments: ${capitalPlan.recommendedInstruments}", bold = true))
            sb.append(paragraph("Stage-Fit Strategic Advisory: ${capitalPlan.stageFitRecommendation}", italic = true, color = "1E293B"))
        }

        sb.append(divider())

        // Footer Verification Seal
        sb.append(paragraph("AUTHENTICATED BY GLOBAL PRODUCT OPERATING SYSTEM", bold = true, color = "64748B", fontSize = 16))
        sb.append(paragraph("Digital Verification ID: GPS-FR-IN-${System.currentTimeMillis()}-VERIFIED", fontSize = 14, color = "94A3B8"))

        sb.append("</w:body>\n")
        sb.append("</w:document>\n")

        return sb.toString()
    }

    private fun paragraph(
        text: String,
        style: String? = null,
        bold: Boolean = false,
        italic: Boolean = false,
        color: String? = null,
        fontSize: Int? = null
    ): String {
        val lines = text.split("\n")
        val sb = StringBuilder()
        for (line in lines) {
            sb.append("<w:p>")
            sb.append("<w:pPr>")
            if (style != null) sb.append("<w:pStyle w:val=\"$style\"/>")
            sb.append("</w:pPr>")
            sb.append("<w:r>")
            sb.append("<w:rPr>")
            if (bold) sb.append("<w:b/>")
            if (italic) sb.append("<w:i/>")
            if (color != null) sb.append("<w:color w:val=\"$color\"/>")
            if (fontSize != null) sb.append("<w:sz w:val=\"$fontSize\"/>")
            sb.append("</w:rPr>")
            sb.append("<w:t xml:space=\"preserve\">${escapeXml(line)}</w:t>")
            sb.append("</w:r>")
            sb.append("</w:p>\n")
        }
        return sb.toString()
    }

    private fun heading(text: String, size: Int): String {
        return paragraph(text, style = "Heading1", bold = true, color = "1C2D4A", fontSize = size)
    }

    private fun divider(): String {
        return "<w:p><w:pPr><w:pBdr><w:bottom w:val=\"single\" w:sz=\"12\" w:space=\"4\" w:color=\"CBD5E1\"/></w:pBdr></w:pPr></w:p>\n"
    }

    private fun buildContentTypesXml(): String {
        return "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\n" +
                "<Types xmlns=\"http://schemas.openxmlformats.org/package/2006/content-types\">\n" +
                "  <Default Extension=\"rels\" ContentType=\"application/vnd.openxmlformats-package.relationships+xml\"/>\n" +
                "  <Default Extension=\"xml\" ContentType=\"application/xml\"/>\n" +
                "  <Override PartName=\"/word/document.xml\" ContentType=\"application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml\"/>\n" +
                "  <Override PartName=\"/word/styles.xml\" ContentType=\"application/vnd.openxmlformats-officedocument.wordprocessingml.styles+xml\"/>\n" +
                "</Types>"
    }

    private fun buildRootRelsXml(): String {
        return "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\n" +
                "<Relationships xmlns=\"http://schemas.openxmlformats.org/package/2006/relationships\">\n" +
                "  <Relationship Id=\"rId1\" Type=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument\" Target=\"word/document.xml\"/>\n" +
                "</Relationships>"
    }

    private fun buildWordRelsXml(): String {
        return "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\n" +
                "<Relationships xmlns=\"http://schemas.openxmlformats.org/package/2006/relationships\">\n" +
                "  <Relationship Id=\"rId1\" Type=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles\" Target=\"styles.xml\"/>\n" +
                "</Relationships>"
    }

    private fun buildStylesXml(): String {
        return "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\n" +
                "<w:styles xmlns:w=\"http://schemas.openxmlformats.org/wordprocessingml/2006/main\">\n" +
                "  <w:style w:type=\"paragraph\" w:default=\"1\" w:styleId=\"Normal\">\n" +
                "    <w:name w:val=\"Normal\"/>\n" +
                "    <w:rPr>\n" +
                "      <w:rFonts w:ascii=\"Calibri\" w:hAnsi=\"Calibri\"/>\n" +
                "      <w:sz w:val=\"22\"/>\n" +
                "      <w:color w:val=\"1E293B\"/>\n" +
                "    </w:rPr>\n" +
                "  </w:style>\n" +
                "</w:styles>"
    }
}
